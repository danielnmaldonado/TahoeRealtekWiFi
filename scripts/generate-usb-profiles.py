#!/usr/bin/env python3
"""Generate immutable C matching facts, retaining unsupported inventory rows."""
import argparse
import hashlib
from pathlib import Path
from usb_wifi_catalog import DEFAULT_DATA, ROOT, c_string, load_catalog, primary_verified, matching_constraints, INTERFACE_FIELDS

def generate(path):
    data, rows = load_catalog(path)
    lines = ['/* Generated by scripts/generate-usb-profiles.py; do not edit. */',
             f'/* Upstream commit: {data["original_commit"]} */',
             f'/* Inventory SHA256: {hashlib.sha256(Path(path).read_bytes()).hexdigest()} */']
    for row in rows:
        m = matching_constraints(row); family = row['candidate_backend_family_from_personality']
        flags = sum(1 << index for index, field in enumerate(INTERFACE_FIELDS) if field in m)
        lines.append('    {0x%04x, 0x%04x, 0x%04x, %u, %u, %u, RTW_WIFI_%s, %u, %s, %u, %u, %u, %u, %u},' % (
            m['idVendor'], m['idProduct'], m.get('bcdDevice',0), int('bcdDevice' in m),
            m['bConfigurationValue'], m['bInterfaceNumber'], family.upper(), int(primary_verified(row)), c_string(row['personality']), flags,
            m.get('bInterfaceClass', 0), m.get('bInterfaceSubClass', 0), m.get('bInterfaceProtocol', 0), row.get('station_band_restriction', 0)))
    return '\n'.join(lines) + '\n'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data',type=Path,default=DEFAULT_DATA)
    parser.add_argument('--output',type=Path,default=ROOT/'src/USBWiFiProfiles.inc')
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args(); result = generate(args.data)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding='utf-8') != result:
            parser.exit(1,'generated USB profile table is stale\n')
    else:
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(result,encoding='utf-8')
if __name__ == '__main__': main()
