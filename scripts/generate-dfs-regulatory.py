#!/usr/bin/env python3
"""Generate DFS20 metadata from hash-pinned official wireless-regdb inputs."""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json
import math

ROOT = Path(__file__).resolve().parents[1]
CHANNELS = (52,56,60,64,100,104,108,112,116,120,124,128,132,136,140)

def generate():
    provenance = json.loads((ROOT / 'src/DFSRegulatory-Upstream.json').read_text())
    base = ROOT / 'vendor/wireless-regdb'
    for entry in provenance['files']:
        value = (base / entry['path']).read_bytes()
        if hashlib.sha256(value).hexdigest() != entry['sha256']:
            raise ValueError('Changed pinned wireless-regdb input: ' + entry['path'])
        blob = b'blob ' + str(len(value)).encode() + b'\0' + value
        if hashlib.sha1(blob).hexdigest() != entry['git_blob_sha1']:
            raise ValueError('Primary git blob mismatch: ' + entry['path'])
    spec = importlib.util.spec_from_file_location('rtw_primary_regdb', base / 'dbparse.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    warnings = []
    with (base / 'db.txt').open() as stream:
        countries = module.DBParser(warn=warnings.append).parse(stream)
    if b'00' not in countries or any(len(cc) != 2 for cc in countries):
        raise ValueError('Invalid primary country keys/world rule')
    lines = ['/* Generated by scripts/generate-dfs-regulatory.py; do not edit.',
             ' * wireless-regdb ' + provenance['commit'] + '; ISC notices in vendor/wireless-regdb/LICENSE. */',
             'static const struct dfs_regulatory_row dfs_regulatory_rows[] = {']
    for cc, country in sorted(countries.items()):
        values = []
        for channel in CHANNELS:
            center = 5000 + 5 * channel
            powers = []
            for permission in country.permissions:
                band = permission.freqband
                # Complete20MHz coverage; no geometry extrapolation, no
                # point-to-point/master permission or NO-OFDM rule reuse.
                if band.start > center - 10 or band.end < center + 10 or band.maxbw < 20:
                    continue
                if permission.flags & ((1 << 0) | (1 << 5) | (1 << 6)):
                    continue
                power = math.floor(permission.power.max_eirp * 100 + 1e-9)
                if not -32767 <= power <= 32767:
                    raise ValueError('Power outside bounded mBm metadata')
                powers.append(power)
            values.append(str(min(powers)) if powers else 'RTW_DFS_REGULATORY_UNAVAILABLE')
        lines.append('    {{%d,%d},{%s}},' % (cc[0],cc[1],','.join(values)))
    lines.append('};')
    return '\n'.join(lines) + '\n', len(countries)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, count = generate()
    destination = ROOT / 'src/DFSRegulatoryTables.inc'
    if args.check:
        if destination.read_text() != text:
            raise SystemExit('Generated DFS regulatory table differs')
    else:
        destination.write_text(text)
    print('Pinned DFS20 country metadata:',count,'domains;',len(CHANNELS),'centers')

if __name__ == '__main__':
    main()
