#!/usr/bin/env python3
"""Generate pinned B/C PHY tables and Linux-parser differential trace goldens.
Only local,hash-verified source is compiled. No device is opened or accessed.
"""
from pathlib import Path
import argparse,hashlib,json,re,subprocess,tempfile
p=argparse.ArgumentParser(description=__doc__);p.add_argument('reference',type=Path);args=p.parse_args()
root=Path(__file__).resolve().parents[1];meta=json.loads((root/'src/RTW88USBDataPath-Upstream.json').read_text());expected={x['path']:x['sha256'] for x in meta['files']}
for name in ['main.h','phy.c','rtw8821c_table.c','rtw8822b_table.c','rtw8822c_table.c']:
 if hashlib.sha256((args.reference/name).read_bytes()).hexdigest()!=expected[name]:raise SystemExit('Upstream source hash mismatch: '+name)
def function(source,name):
 start=source.index(name+'(');start=source.rfind('\n',0,start)+1
 # The return type is on the same line for both reference functions.
 begin=source.index('{',start);level=1;end=begin+1
 while level:
  level+=(source[end]=='{')-(source[end]=='}');end+=1
 return source[start:end]
main=(args.reference/'main.h').read_text();phy=(args.reference/'phy.c').read_text()
cond=re.search(r'struct rtw_phy_cond \{.*?\n\};',main,re.S).group(0);cond2=re.search(r'struct rtw_phy_cond2 \{.*?\n\};',main,re.S).group(0)
union=phy[phy.index('struct phy_cfg_pair {'):phy.index('static const u32 db_invert_table')]
checker=function(phy,'check_positive');parser=function(phy,'rtw_parse_tbl_phy_cond')
header='''#include <stdint.h>
#include <stdbool.h>
#include <stdio.h>
typedef uint8_t u8;typedef uint32_t u32;
#define __LITTLE_ENDIAN 1
#define __packed __attribute__((packed))
#define BIT(n) (1U<<(n))
#define BUILD_BUG_ON(x) _Static_assert(!(x),"size")
#define RTW_CHIP_TYPE_8812A 1
#define RTW_CHIP_TYPE_8821A 2
'''+cond+'\n'+cond2+'\n'+union+'''
struct rtw_dev;
struct rtw_table {const void*data;unsigned size;void(*do_cfg)(struct rtw_dev*,const struct rtw_table*,u32,u32);};
struct rtw_hal {struct rtw_phy_cond phy_cond;struct rtw_phy_cond2 phy_cond2;};
struct rtw_dev {struct rtw_hal hal;struct {unsigned id;}chip_store;void*chip;};
'''
# Reference checker expects a typed chip pointer; keep its branch unchanged.
header=header.replace('struct rtw_dev {struct rtw_hal hal;struct {unsigned id;}chip_store;void*chip;};','struct chip {unsigned id;};struct rtw_dev {struct rtw_hal hal;struct chip*chip;};')
header+=checker+'\n'+parser+'''
static uint64_t hash;static unsigned count,kind,path;
static void emit(struct rtw_dev*d,const struct rtw_table*t,u32 a,u32 v){(void)d;(void)t;uint32_t words[4]={kind,path,a,v};for(unsigned j=0;j<4;j++)for(unsigned k=0;k<4;k++){hash^=(uint8_t)(words[j]>>(k*8));hash*=UINT64_C(1099511628211);}count++;}
'''
result=['/* SPDX-License-Identifier: GPL-2.0 OR BSD-3-Clause */','/* Copyright(c)2018-2019 Realtek Corporation. Hash-pinned unmodified PHY table words. */'];goldens=['/* Generated by the complete pinned Linux check_positive/rtw_parse_tbl_phy_cond functions. */']
family={'8821c':'RTW_WIFI_RTL8821CU','8822b':'RTW_WIFI_RTL8822BU','8822c':'RTW_WIFI_RTL8822CU'}
for chip,rfes in [('8821c',[0,2,4,6]),('8822b',[2,3,5]),('8822c',list(range(7)))]:
 source=(args.reference/('rtw'+chip+'_table.c')).read_text();arrays={}
 names=['mac','bb','agc']+(['agc_btg_type2'] if chip=='8821c' else [])+(['array_mp_cal_init'] if chip=='8822c' else [])+(['rf_b','rf_a'] if chip=='8822c' else ['rf_a']+(['rf_b'] if chip=='8822b' else []))
 for short in names:
  name='rtw'+chip+'_'+short;match=re.search(r'static const u32 '+name+r'\[\] = \{(.*?)\n\};',source,re.S);assert match,name
  body=re.sub(r'/\*.*?\*/|//[^\n]*','',match.group(1),flags=re.S);words=re.findall(r'0x[0-9a-fA-F]+',body);assert not re.sub(r'0x[0-9a-fA-F]+|[\s,]','',body),name;assert len(words)%2==0
  arrays[short]=(name,words);result.append('static const uint32_t '+name+'[] = {\n'+(',\n'.join(' '+', '.join(words[i:i+2]) for i in range(0,len(words),2)) if words else ' 0')+'\n};')
 result.append('static const struct rtw88_phy_table tables_'+chip+'[] = {')
 for short in names:
  name,words=arrays[short];kind=0 if short=='mac' else 2 if short.startswith('agc') else 3 if short.startswith('rf_') else 1;path=1 if short=='rf_b' else 0;btg=1 if short=='agc_btg_type2' else 0;rfk=1 if short=='array_mp_cal_init' else 0
  result.append(' {%u,%u,%u,%u,%s,%u},'%(kind,path,btg,rfk,name,len(words)))
 result.append('};')
 body=header+'\n'+'\n'.join('static const u32 '+name+'[]={'+','.join(words or ['0'])+'};' for name,words in arrays.values())+'\nint main(void){struct chip chip={0};struct rtw_dev d={0};d.chip=&chip;\n'
 for cut in [0,2,6]:
  for pkg in [0,1]:
   for rfe in rfes:
    body+='hash=UINT64_C(1469598103934665603);count=0;d.hal.phy_cond=(struct rtw_phy_cond){.cut='+str(cut or 15)+',.pkg='+str(pkg or 15)+',.intf=2,.rfe='+str(rfe)+'};\n'
    for short in names:
     if short=='agc_btg_type2' and rfe not in [2,4]:continue
     name,words=arrays[short];k=0 if short=='mac' else 2 if short.startswith('agc') else 3 if short.startswith('rf_') else 1;path=1 if short=='rf_b' else 0
     body+='{struct rtw_table t={'+name+','+str(len(words))+',emit};kind='+str(k)+';path='+str(path)+';rtw_parse_tbl_phy_cond(&d,&t);}\n'
    body+='printf(" {'+family[chip]+','+str(cut)+','+str(pkg)+','+str(rfe)+',UINT64_C(0x%016llx),%u},\\n",(unsigned long long)hash,count);\n'
 body+='return 0;}\n'
 with tempfile.TemporaryDirectory() as temp:
  c=Path(temp)/'extract.c';exe=Path(temp)/'extract';c.write_text(body);subprocess.run(['xcrun','clang','-std=c11','-Wno-macro-redefined',str(c),'-o',str(exe)],check=True);goldens.extend(subprocess.check_output([str(exe)],text=True).splitlines())
 print(chip,sum(len(x[1]) for x in arrays.values()),'pinned PHY words')
(root/'src/RTW88PHYTables.inc').write_text('\n'.join(result)+'\n');(root/'tests/RTW88PHYGoldens.inc').write_text('\n'.join(goldens)+'\n')
